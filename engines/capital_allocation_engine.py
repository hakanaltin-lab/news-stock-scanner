"""
V7.4 AURORA Regime-Aware Capital Allocation Engine

Purpose:
- Use cash generated by the V7.1 rebalancing plan
- Maintain a market-regime-aware minimum cash reserve
- Scale new position size according to market regime
- Block weaker allocations in defensive regimes
- Allocate only to actionable new opportunities
- Respect BUY / ACCUMULATE position limits
- Require price to be inside the recommended entry zone
- Use whole-share sizing
- Never assume existing account cash
- Never send broker orders

Important:
This engine uses only cash generated by the AURORA
rebalancing plan. Existing brokerage cash is unknown.
"""

import math


MIN_CASH_RESERVE_WEIGHT = 20.0

BUY_TARGET_WEIGHT = 5.0

ACCUMULATE_TARGET_WEIGHT = 4.0

MAX_NEW_POSITION_WEIGHT = 5.0

MIN_ALLOCATION_VALUE = 100.0


def safe_float(
    value,
    default=0.0
):

    try:

        return float(
            value
        )

    except (
        TypeError,
        ValueError
    ):

        return default


def calculate_weight(
    value,
    portfolio_value
):

    if portfolio_value <= 0:

        return 0.0


    return (
        value
        /
        portfolio_value
        *
        100
    )


def get_target_weight(
    action,
    regime_policy=None
):

    regime_policy = (
        regime_policy
        or
        {}
    )


    size_multiplier = safe_float(
        regime_policy.get(
            "position_size_multiplier",
            1.0
        ),
        1.0
    )


    max_new_position_weight = safe_float(
        regime_policy.get(
            "max_new_position_weight_pct",
            MAX_NEW_POSITION_WEIGHT
        ),
        MAX_NEW_POSITION_WEIGHT
    )


    if action == "BUY":

        return min(
            BUY_TARGET_WEIGHT
            *
            size_multiplier,
            max_new_position_weight
        )


    if action == "ACCUMULATE":

        return min(
            ACCUMULATE_TARGET_WEIGHT
            *
            size_multiplier,
            max_new_position_weight
        )


    return 0.0


def price_inside_entry_zone(
    price,
    decision
):

    entry_zone = (
        decision.get(
            "entry_zone",
            {}
        )
        or
        {}
    )


    low = safe_float(
        entry_zone.get(
            "low",
            0
        )
    )


    high = safe_float(
        entry_zone.get(
            "high",
            0
        )
    )


    if (
        low <= 0
        or high <= 0
        or price <= 0
    ):

        return False


    return (
        price >= low
        and
        price <= high
    )


def opportunity_priority(
    opportunity
):

    action = opportunity.get(
        "action",
        ""
    )


    action_priority = {

        "BUY":
        2,

        "ACCUMULATE":
        1

    }.get(
        action,
        0
    )


    scores = opportunity.get(
        "scores",
        {}
    )


    decision = opportunity.get(
        "decision",
        {}
    )


    alpha_score = safe_float(
        scores.get(
            "alpha_score",
            0
        )
    )


    confidence = safe_float(
        decision.get(
            "confidence",
            0
        )
    )


    return (
        action_priority,
        alpha_score,
        confidence
    )


def build_candidate_allocation(
    opportunity,
    portfolio_value,
    available_deployable_cash,
    regime_policy=None
):

    regime_policy = (
        regime_policy
        or
        {}
    )


    ticker = opportunity.get(
        "ticker",
        "UNKNOWN"
    )


    action = opportunity.get(
        "action",
        "WATCH"
    )


    market = opportunity.get(
        "market",
        {}
    )


    scores = opportunity.get(
        "scores",
        {}
    )


    decision = opportunity.get(
        "decision",
        {}
    )


    price = safe_float(
        market.get(
            "last_price",
            0
        )
    )


    alpha_score = safe_float(
        scores.get(
            "alpha_score",
            0
        )
    )


    confidence = safe_float(
        decision.get(
            "confidence",
            0
        )
    )


    risk_score = safe_float(
        scores.get(
            "risk_score",
            0
        )
    )


    target_weight = (
        get_target_weight(
            action,
            regime_policy=regime_policy
        )
    )


    target_value = (
        portfolio_value
        *
        target_weight
        /
        100
    )


    base_result = {

        "ticker":
        ticker,

        "action":
        action,

        "sector":
        opportunity.get(
            "sector"
        ),

        "price":
        round(
            price,
            2
        ),

        "alpha_score":
        round(
            alpha_score,
            2
        ),

        "confidence":
        round(
            confidence,
            1
        ),

        "risk_score":
        round(
            risk_score,
            1
        ),

        "target_weight_pct":
        round(
            target_weight,
            2
        ),

        "target_value":
        round(
            target_value,
            2
        ),

        "suggested_shares":
        0,

        "allocated_value":
        0.0,

        "projected_weight_pct":
        0.0,

        "allocation_status":
        "NO_ALLOCATION",

        "reason":
        "",

        "entry_zone":
        decision.get(
            "entry_zone"
        ),

        "stop_loss":
        decision.get(
            "stop_loss"
        ),

        "target_price":
        decision.get(
            "target_price"
        ),

        "risk_reward":
        decision.get(
            "risk_reward"
        )
    }


    if action not in [
        "BUY",
        "ACCUMULATE"
    ]:

        base_result[
            "reason"
        ] = (
            "Opportunity is not BUY or ACCUMULATE"
        )

        return base_result


    buy_alpha_min = safe_float(
        regime_policy.get(
            "buy_alpha_min",
            0
        )
    )


    accumulate_alpha_min = safe_float(
        regime_policy.get(
            "accumulate_alpha_min",
            0
        )
    )


    minimum_risk_score = safe_float(
        regime_policy.get(
            "minimum_risk_score",
            0
        )
    )


    required_alpha = (
        buy_alpha_min
        if action == "BUY"
        else
        accumulate_alpha_min
    )


    if (
        required_alpha > 0
        and
        alpha_score < required_alpha
    ):

        base_result[
            "allocation_status"
        ] = (
            "REGIME_BLOCK"
        )

        base_result[
            "reason"
        ] = (
            "Alpha score is below the current market-regime threshold"
        )

        return base_result


    if (
        minimum_risk_score > 0
        and
        risk_score < minimum_risk_score
    ):

        base_result[
            "allocation_status"
        ] = (
            "REGIME_BLOCK"
        )

        base_result[
            "reason"
        ] = (
            "Risk score is below the current market-regime threshold"
        )

        return base_result


    if price <= 0:

        base_result[
            "reason"
        ] = (
            "Invalid market price"
        )

        return base_result


    if not price_inside_entry_zone(
        price,
        decision
    ):

        base_result[
            "allocation_status"
        ] = (
            "WAIT_FOR_ENTRY"
        )

        base_result[
            "reason"
        ] = (
            "Current price is outside recommended entry zone"
        )

        return base_result


    if available_deployable_cash < MIN_ALLOCATION_VALUE:

        base_result[
            "allocation_status"
        ] = (
            "CASH_LIMIT"
        )

        base_result[
            "reason"
        ] = (
            "Deployable cash below minimum allocation threshold"
        )

        return base_result


    allocation_budget = min(
        target_value,
        available_deployable_cash
    )


    shares = math.floor(
        allocation_budget
        /
        price
    )


    if shares <= 0:

        base_result[
            "allocation_status"
        ] = (
            "CASH_LIMIT"
        )

        base_result[
            "reason"
        ] = (
            "Available cash is insufficient for one whole share"
        )

        return base_result


    allocated_value = (
        shares
        *
        price
    )


    if allocated_value < MIN_ALLOCATION_VALUE:

        base_result[
            "allocation_status"
        ] = (
            "NO_ALLOCATION"
        )

        base_result[
            "reason"
        ] = (
            "Allocation value below minimum threshold"
        )

        return base_result


    projected_weight = (
        calculate_weight(
            allocated_value,
            portfolio_value
        )
    )


    base_result[
        "suggested_shares"
    ] = shares


    base_result[
        "allocated_value"
    ] = round(
        allocated_value,
        2
    )


    base_result[
        "projected_weight_pct"
    ] = round(
        projected_weight,
        2
    )


    base_result[
        "allocation_status"
    ] = (
        "ALLOCATE"
    )


    base_result[
        "reason"
    ] = (
        "Actionable opportunity inside entry zone and within capital limits"
    )


    return base_result


def build_capital_allocation_plan(
    rebalancing_result,
    opportunity_analysis,
    market_regime_result=None
):

    market_regime_result = (
        market_regime_result
        or
        {}
    )


    regime_name = market_regime_result.get(
        "regime",
        "NORMAL"
    )


    regime_score = safe_float(
        market_regime_result.get(
            "regime_score",
            50
        ),
        50
    )


    regime_policy = (
        market_regime_result.get(
            "policy",
            {}
        )
        or
        {}
    )


    minimum_cash_reserve_weight = safe_float(
        regime_policy.get(
            "minimum_cash_reserve_pct",
            MIN_CASH_RESERVE_WEIGHT
        ),
        MIN_CASH_RESERVE_WEIGHT
    )


    max_new_position_weight = safe_float(
        regime_policy.get(
            "max_new_position_weight_pct",
            MAX_NEW_POSITION_WEIGHT
        ),
        MAX_NEW_POSITION_WEIGHT
    )


    portfolio_value = safe_float(
        rebalancing_result.get(
            "portfolio_value",
            0
        )
    )


    generated_cash = safe_float(
        rebalancing_result.get(
            "estimated_net_cash_generated",
            0
        )
    )


    reserve_target_value = (
        portfolio_value
        *
        minimum_cash_reserve_weight
        /
        100
    )


    deployable_cash = max(
        0,
        generated_cash
        -
        reserve_target_value
    )


    actionable = list(
        opportunity_analysis.get(
            "top_actionable",
            []
        )
        or
        []
    )


    actionable.sort(
        key=opportunity_priority,
        reverse=True
    )


    allocation_plan = []

    remaining_deployable_cash = (
        deployable_cash
    )


    total_new_allocations = 0.0


    for opportunity in actionable:

        allocation = (
            build_candidate_allocation(
                opportunity=opportunity,
                portfolio_value=portfolio_value,
                available_deployable_cash=remaining_deployable_cash,
                regime_policy=regime_policy
            )
        )


        allocation_plan.append(
            allocation
        )


        if (
            allocation.get(
                "allocation_status"
            )
            ==
            "ALLOCATE"
        ):

            allocated_value = safe_float(
                allocation.get(
                    "allocated_value",
                    0
                )
            )


            total_new_allocations += (
                allocated_value
            )


            remaining_deployable_cash = max(
                0,
                remaining_deployable_cash
                -
                allocated_value
            )


    projected_cash_after_allocations = max(
        0,
        generated_cash
        -
        total_new_allocations
    )


    projected_cash_weight = (
        calculate_weight(
            projected_cash_after_allocations,
            portfolio_value
        )
    )


    reserve_weight = (
        calculate_weight(
            reserve_target_value,
            portfolio_value
        )
    )


    reserve_status = (
        "PASS"
        if
        projected_cash_after_allocations
        >=
        reserve_target_value
        else
        "BELOW_TARGET"
    )


    return {

        "engine":
        "V7.4 Regime-Aware Capital Allocation Engine",

        "market_regime":
        regime_name,

        "market_regime_score":
        round(
            regime_score,
            1
        ),

        "regime_policy":
        regime_policy,

        "portfolio_value":
        round(
            portfolio_value,
            2
        ),

        "generated_cash_available":
        round(
            generated_cash,
            2
        ),

        "minimum_cash_reserve_pct":
        round(
            minimum_cash_reserve_weight,
            2
        ),

        "minimum_cash_reserve_value":
        round(
            reserve_target_value,
            2
        ),

        "initial_deployable_cash":
        round(
            deployable_cash,
            2
        ),

        "new_opportunity_allocation":
        round(
            total_new_allocations,
            2
        ),

        "projected_cash_after_allocations":
        round(
            projected_cash_after_allocations,
            2
        ),

        "projected_cash_weight_pct":
        round(
            projected_cash_weight,
            2
        ),

        "reserve_target_weight_pct":
        round(
            reserve_weight,
            2
        ),

        "cash_reserve_status":
        reserve_status,

        "max_new_position_weight_pct":
        round(
            max_new_position_weight,
            2
        ),

        "allocation_plan":
        allocation_plan,

        "note":
        (
            "Cash calculations use only cash generated by the rebalancing plan. "
            "Minimum reserve and new-position sizing are adjusted by market regime. "
            "Existing brokerage cash is not included."
        )
    }
