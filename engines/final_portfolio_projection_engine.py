"""
V7.3 AURORA Final Portfolio Projection Engine

Purpose:
- Combine V7.1 rebalancing results
- Combine V7.2 new opportunity allocations
- Add projected cash as an explicit portfolio component
- Produce the final post-trade portfolio
- Recalculate final position and theme weights
- Reconcile final projected value back to the original portfolio value

Important:
- Existing brokerage cash is not included.
- Cash shown here is generated by the modeled rebalancing plan.
- No broker orders are sent.
"""

RECONCILIATION_TOLERANCE = 1.00
THEME_CONCENTRATION_LIMIT = 35.0


def safe_float(value, default=0.0):
    try:
        return float(value)
    except (TypeError, ValueError):
        return default


def calculate_weight(value, portfolio_value):
    if portfolio_value <= 0:
        return 0.0

    return value / portfolio_value * 100


def calculate_existing_final_shares(
    current_shares,
    trade_action,
    suggested_shares
):
    current_shares = safe_float(current_shares)
    suggested_shares = safe_float(suggested_shares)

    if trade_action == "SELL_ALL":
        return 0.0

    if trade_action == "SELL_PARTIAL":
        return max(
            0.0,
            current_shares - suggested_shares
        )

    if trade_action == "BUY_TO_TARGET":
        return current_shares + suggested_shares

    return current_shares


def get_normalized_sector(portfolio_item):
    sector_analysis = portfolio_item.get(
        "sector",
        {}
    )

    if isinstance(sector_analysis, dict):
        sector_name = sector_analysis.get(
            "sector"
        )

        if sector_name:
            return sector_name

    holding = portfolio_item.get(
        "holding",
        {}
    )

    return (
        holding.get("sector")
        or
        "Unknown"
    )


def build_final_portfolio_projection(
    portfolio_results,
    rebalancing_result,
    capital_allocation_result
):
    portfolio_value = safe_float(
        rebalancing_result.get(
            "portfolio_value",
            0
        )
    )

    rebalance_plan = (
        rebalancing_result.get(
            "rebalancing_plan",
            []
        )
        or
        []
    )

    rebalance_lookup = {
        item.get("ticker"): item
        for item in rebalance_plan
        if item.get("ticker")
    }

    final_positions = []

    # =====================================================
    # 1. EXISTING POSITIONS AFTER REBALANCING
    # =====================================================

    for item in portfolio_results:
        ticker = item.get(
            "ticker",
            "UNKNOWN"
        )

        management = item.get(
            "portfolio_management",
            {}
        )

        position = management.get(
            "position",
            {}
        )

        holding = item.get(
            "holding",
            {}
        )

        current_shares = safe_float(
            position.get(
                "shares",
                0
            )
        )

        current_price = safe_float(
            position.get(
                "current_price",
                0
            )
        )

        current_value = safe_float(
            position.get(
                "current_value",
                0
            )
        )

        plan = rebalance_lookup.get(
            ticker,
            {}
        )

        trade_action = plan.get(
            "trade_action",
            "NO_TRADE"
        )

        suggested_shares = safe_float(
            plan.get(
                "suggested_shares",
                0
            )
        )

        final_shares = calculate_existing_final_shares(
            current_shares=current_shares,
            trade_action=trade_action,
            suggested_shares=suggested_shares
        )

        final_value = safe_float(
            plan.get(
                "projected_value",
                current_value
            )
        )

        if (
            final_value <= 0
            and
            final_shares <= 0
        ):
            continue

        final_weight = calculate_weight(
            final_value,
            portfolio_value
        )

        final_positions.append({
            "ticker": ticker,
            "source": "EXISTING",
            "sector": get_normalized_sector(item),
            "theme": (
                holding.get("theme")
                or
                "Unknown"
            ),
            "current_shares": round(
                current_shares,
                4
            ),
            "final_shares": round(
                final_shares,
                4
            ),
            "price": round(
                current_price,
                2
            ),
            "current_value": round(
                current_value,
                2
            ),
            "final_value": round(
                final_value,
                2
            ),
            "value_change": round(
                final_value - current_value,
                2
            ),
            "final_weight_pct": round(
                final_weight,
                2
            ),
            "portfolio_action": item.get(
                "portfolio_action",
                "WATCH"
            ),
            "trade_action": trade_action
        })

    # =====================================================
    # 2. NEW POSITIONS FROM CAPITAL ALLOCATION
    # =====================================================

    allocation_plan = (
        capital_allocation_result.get(
            "allocation_plan",
            []
        )
        or
        []
    )

    for allocation in allocation_plan:
        if (
            allocation.get(
                "allocation_status"
            )
            !=
            "ALLOCATE"
        ):
            continue

        ticker = allocation.get(
            "ticker",
            "UNKNOWN"
        )

        allocated_value = safe_float(
            allocation.get(
                "allocated_value",
                0
            )
        )

        if allocated_value <= 0:
            continue

        final_weight = calculate_weight(
            allocated_value,
            portfolio_value
        )

        final_positions.append({
            "ticker": ticker,
            "source": "NEW_ALLOCATION",
            "sector": (
                allocation.get("sector")
                or
                "Unknown"
            ),
            "theme": (
                allocation.get("sector")
                or
                "Unknown"
            ),
            "current_shares": 0,
            "final_shares": safe_float(
                allocation.get(
                    "suggested_shares",
                    0
                )
            ),
            "price": round(
                safe_float(
                    allocation.get(
                        "price",
                        0
                    )
                ),
                2
            ),
            "current_value": 0.0,
            "final_value": round(
                allocated_value,
                2
            ),
            "value_change": round(
                allocated_value,
                2
            ),
            "final_weight_pct": round(
                final_weight,
                2
            ),
            "portfolio_action": allocation.get(
                "action",
                "WATCH"
            ),
            "trade_action": "NEW_POSITION"
        })

    # =====================================================
    # 3. PROJECTED CASH
    # =====================================================

    projected_cash = safe_float(
        capital_allocation_result.get(
            "projected_cash_after_allocations",
            0
        )
    )

    cash_weight = calculate_weight(
        projected_cash,
        portfolio_value
    )

    if projected_cash > 0:
        final_positions.append({
            "ticker": "CASH",
            "source": "CASH",
            "sector": "Cash",
            "theme": "Cash",
            "current_shares": 0,
            "final_shares": 0,
            "price": 1.0,
            "current_value": 0.0,
            "final_value": round(
                projected_cash,
                2
            ),
            "value_change": round(
                projected_cash,
                2
            ),
            "final_weight_pct": round(
                cash_weight,
                2
            ),
            "portfolio_action": "RESERVE",
            "trade_action": "HOLD_CASH"
        })

    # =====================================================
    # 4. FINAL THEME EXPOSURE
    # =====================================================

    theme_values = {}

    for position in final_positions:
        theme = (
            position.get("theme")
            or
            "Unknown"
        )

        final_value = safe_float(
            position.get(
                "final_value",
                0
            )
        )

        theme_values[theme] = (
            theme_values.get(
                theme,
                0
            )
            +
            final_value
        )

    final_theme_exposure = {}
    concentration_alerts = []

    for theme, value in theme_values.items():
        weight = calculate_weight(
            value,
            portfolio_value
        )

        final_theme_exposure[theme] = {
            "value": round(
                value,
                2
            ),
            "weight_pct": round(
                weight,
                2
            )
        }

        if (
            theme != "Cash"
            and
            weight > THEME_CONCENTRATION_LIMIT
        ):
            concentration_alerts.append({
                "theme": theme,
                "weight_pct": round(
                    weight,
                    2
                ),
                "limit_pct": THEME_CONCENTRATION_LIMIT
            })

    # =====================================================
    # 5. RECONCILIATION
    # =====================================================

    final_positions.sort(
        key=lambda item: safe_float(
            item.get(
                "final_weight_pct",
                0
            )
        ),
        reverse=True
    )

    final_projected_value = sum(
        safe_float(
            item.get(
                "final_value",
                0
            )
        )
        for item in final_positions
    )

    reconciliation_difference = (
        final_projected_value
        -
        portfolio_value
    )

    total_weight_pct = sum(
        safe_float(
            item.get(
                "final_weight_pct",
                0
            )
        )
        for item in final_positions
    )

    reconciliation_status = (
        "PASS"
        if
        abs(
            reconciliation_difference
        )
        <=
        RECONCILIATION_TOLERANCE
        else
        "REVIEW"
    )

    non_cash_positions = [
        item
        for item in final_positions
        if item.get("source") != "CASH"
    ]

    largest_position = None

    if non_cash_positions:
        largest_position = max(
            non_cash_positions,
            key=lambda item: safe_float(
                item.get(
                    "final_weight_pct",
                    0
                )
            )
        )

    invested_value = max(
        0,
        final_projected_value
        -
        projected_cash
    )

    return {
        "engine":
        "V7.3 Final Portfolio Projection Engine",

        "portfolio_value":
        round(
            portfolio_value,
            2
        ),

        "final_projected_value":
        round(
            final_projected_value,
            2
        ),

        "invested_value":
        round(
            invested_value,
            2
        ),

        "invested_weight_pct":
        round(
            calculate_weight(
                invested_value,
                portfolio_value
            ),
            2
        ),

        "cash_value":
        round(
            projected_cash,
            2
        ),

        "cash_weight_pct":
        round(
            cash_weight,
            2
        ),

        "final_position_count":
        len(
            non_cash_positions
        ),

        "new_position_count":
        len([
            item
            for item in final_positions
            if item.get(
                "source"
            )
            ==
            "NEW_ALLOCATION"
        ]),

        "largest_position":
        (
            {
                "ticker":
                largest_position.get(
                    "ticker"
                ),

                "weight_pct":
                largest_position.get(
                    "final_weight_pct"
                ),

                "value":
                largest_position.get(
                    "final_value"
                )
            }
            if largest_position
            else None
        ),

        "total_weight_pct":
        round(
            total_weight_pct,
            2
        ),

        "reconciliation_difference":
        round(
            reconciliation_difference,
            2
        ),

        "reconciliation_status":
        reconciliation_status,

        "final_theme_exposure":
        final_theme_exposure,

        "concentration_alerts":
        concentration_alerts,

        "final_positions":
        final_positions,

        "note":
        (
            "Projection combines modeled V7.1 rebalancing, regime/event/correlation-aware new allocations "
            "and cash generated by those modeled trades. Existing brokerage cash "
            "is not included."
        )
    }
